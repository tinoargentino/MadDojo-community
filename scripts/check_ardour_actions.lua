assert(arg[1] and arg[2], "Pass a test session and the Dojo script directory")
assert(load_session(arg[1], ""), "Could not open the test session")
ardour = function(_) end
local function action(name)
  dofile(arg[2] .. "/" .. name .. ".lua")
  factory()()
  sleep(.08) -- Controls cross to the native audio thread on its next cycle.
end
local guide = Session:route_by_name("Guide vocal")
assert(guide:mute_control():get_value() == 0)
action("dojo_vocal_mute")
assert(guide:mute_control():get_value() == 1)
action("dojo_vocal_mute")
assert(guide:mute_control():get_value() == 0)
local original_gain = guide:gain_control():get_value()
action("dojo_vocal_down")
assert(math.abs(guide:gain_control():get_value() - (original_gain - .05)) < .0001)
action("dojo_vocal_up")
assert(math.abs(guide:gain_control():get_value() - original_gain) < .0001)
local loop = Session:locations():auto_loop_location()
for _, bars in ipairs({1,2,4}) do
  Session:request_stop(false, true, ARDOUR.TransportRequestSource.TRS_UI)
  sleep(.3)
  Session:request_locate(0, false, ARDOUR.LocateTransportDisposition.MustStop, ARDOUR.TransportRequestSource.TRS_UI)
  sleep(.12)
  action("dojo_loop_" .. bars .. "_bar")
  sleep(.12)
  local actual = loop:length():samples() / Session:nominal_sample_rate()
  assert(math.abs(actual - bars * 2.5) < .001, "Incorrect warm-up bar loop")
  print("LOOP ACTION", bars, "bars", actual, "seconds")
end
Session:request_stop(false, true, ARDOUR.TransportRequestSource.TRS_UI)
sleep(.3)
Session:request_play_loop(false, false)
sleep(.12)
action("dojo_restart_phrase")
sleep(.12)
local voice = Session:route_by_name("Your voice"):to_track()
voice:rec_enable_control():set_value(1, PBD.GroupControlDisposition.NoGroup)
Session:maybe_enable_record(false)
Session:request_roll(ARDOUR.TransportRequestSource.TRS_UI)
sleep(.6)
Session:request_stop(false, true, ARDOUR.TransportRequestSource.TRS_UI)
sleep(.5)
assert(voice:playlist():region_list():size() > 0, "Native recording did not create a take")
print("VOICE TAKE REGIONS", voice:playlist():region_list():size())
voice:rec_enable_control():set_value(0, PBD.GroupControlDisposition.NoGroup)
Session:save_state("")
